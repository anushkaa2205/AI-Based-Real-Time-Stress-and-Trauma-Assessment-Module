/**
 * `npm run seed` (task 1.10, DATABASE.md §10.4). Safe to run again.
 *  - a few states and districts
 *  - one staff user per role (fresh random password every run)
 *  - TOTP secrets for supervisor/admin roles (kept between runs; --reset-totp makes new ones)
 *  - scoring config v1 from core/scoring/defaultConfig.ts (Appendices A–C), active
 *  - one API client for the integration example (key shown once, when created)
 *
 * Passwords, TOTP URIs and the API key go to web/.seed-output/ (git-ignored),
 * never to the console. All data is synthetic (CLAUDE.md rule 11).
 * Synthetic cases arrive with the evaluation scenarios (Phase E).
 */
import "./load-env";
import { createHash, randomBytes } from "node:crypto";
import { mkdirSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import mongoose, { type Types } from "mongoose";
import { hashPassword } from "@/core/auth/password";
import { newTotpSecret, roleRequiresTotp, totpUri } from "@/core/auth/totp";
import { encrypt } from "@/core/privacy/crypto";
import { db } from "@/lib/db";
import { ApiClient, District, ROLES, ScoringConfig, State, User, type Role } from "@/models";
import { validateConfig } from "@/core/scoring/config";
import { DEFAULT_CONFIG } from "@/core/scoring/defaultConfig";

const RESET_TOTP = process.argv.includes("--reset-totp");
const OUT_DIR = resolve(process.cwd(), ".seed-output");
const EMAIL_DOMAIN = "staff.nivara.test";

const STATES = [
  { code: "MH", name: "Maharashtra", districts: [["MH-PUN", "Pune"], ["MH-NAG", "Nagpur"]] },
  { code: "TN", name: "Tamil Nadu", districts: [["TN-CHN", "Chennai"], ["TN-MDU", "Madurai"]] },
  { code: "WB", name: "West Bengal", districts: [["WB-KOL", "Kolkata"]] },
  { code: "UP", name: "Uttar Pradesh", districts: [["UP-LKO", "Lucknow"]] },
] as const;

const STAFF_NAMES: Record<Role, string> = {
  OPERATOR: "Nivara Operator",
  NHAA_SUPERVISOR: "Nivara Supervisor",
  COUNSELLOR: "Nivara Counsellor",
  DISTRICT_OFFICER: "Nivara District Officer",
  POLICE_LIAISON: "Nivara Police Liaison",
  WELFARE_OFFICER: "Nivara Welfare Officer",
  STATE_ADMIN: "Nivara State Admin",
  MINISTRY_ADMIN: "Nivara Ministry Admin",
  SYS_ADMIN: "Nivara System Admin",
  AUDITOR: "Nivara Auditor",
};

const DISTRICT_ROLES: readonly Role[] = ["DISTRICT_OFFICER", "POLICE_LIAISON", "WELFARE_OFFICER"];

async function seedGeography() {
  const districts = new Map<string, { id: Types.ObjectId; stateId: Types.ObjectId }>();
  for (const s of STATES) {
    const state = await State.findOneAndUpdate({ code: s.code }, { $set: { name: s.name } }, { upsert: true, returnDocument: "after" });
    for (const [code, name] of s.districts) {
      const d = await District.findOneAndUpdate(
        { code },
        { $set: { name, stateId: state._id } },
        { upsert: true, returnDocument: "after" },
      );
      districts.set(code, { id: d._id, stateId: state._id });
    }
  }
  console.log(`states: ${STATES.length}, districts: ${districts.size}`);
  return districts;
}

async function seedUsers(home: { id: Types.ObjectId; stateId: Types.ObjectId }) {
  const lines: string[] = ["# Seeded staff accounts (synthetic). Regenerated by every `npm run seed`.", ""];
  for (const role of ROLES) {
    const email = `${role.toLowerCase().replace(/_/g, "-")}@${EMAIL_DOMAIN}`;
    const password = randomBytes(12).toString("base64url");
    const existing = await User.findOne({ email }).select("+totpSecretEnc").lean();

    const set: Record<string, unknown> = {
      name: STAFF_NAMES[role],
      role,
      passwordHash: await hashPassword(password),
      isActive: true,
      languages: ["en", "hi"],
      districtId: DISTRICT_ROLES.includes(role) ? home.id : null,
      stateId: DISTRICT_ROLES.includes(role) || role === "STATE_ADMIN" ? home.stateId : null,
    };

    let totp = "";
    if (roleRequiresTotp(role)) {
      if (!existing?.totpSecretEnc || RESET_TOTP) {
        const secret = newTotpSecret();
        set.totpSecretEnc = encrypt(secret);
        totp = totpUri(secret, email);
      } else {
        totp = "(unchanged; run `npm run seed -- --reset-totp` for a new one)";
      }
    }

    await User.updateOne({ email }, { $set: set }, { upsert: true });
    lines.push(`${role}`, `  email:    ${email}`, `  password: ${password}`);
    if (totp) lines.push(`  totp:     ${totp}`);
    lines.push("");
  }
  writeFileSync(resolve(OUT_DIR, "staff-credentials.txt"), lines.join("\n"), { mode: 0o600 });
  console.log(`users: ${ROLES.length} (credentials written to .seed-output/staff-credentials.txt)`);
}

async function seedScoringConfig() {
  const admin = await User.findOne({ role: "SYS_ADMIN" }).lean();
  if (!admin) throw new Error("SYS_ADMIN user missing");
  const checked = validateConfig(DEFAULT_CONFIG);
  if (!checked.ok) throw new Error(`default scoring config is invalid: ${checked.errors.join("; ")}`);
  const c = checked.config;
  const exists = await ScoringConfig.exists({ version: c.version });
  if (!exists) {
    await ScoringConfig.updateMany({ isActive: true }, { $set: { isActive: false } });
    await ScoringConfig.create({
      version: c.version,
      dimensionWeights: c.dimensionWeights,
      sourceWeights: c.sourceWeights,
      voiceOnlyCap: c.voiceOnlyCap,
      bandThresholds: c.bandThresholds,
      safetyOverrides: c.safetyOverrides,
      recommendationRules: c.recommendationRules,
      alertPolicy: { ...c.alertPolicy, escalationChain: [...c.alertPolicy.escalationChain] },
      isActive: true,
      notes: "Defaults from REQUIREMENTS.md Appendices A–C",
      createdById: admin._id,
    });
    console.log(`scoring config: v${c.version} created and active`);
  } else {
    console.log(`scoring config: v${c.version} already present (append-only, left unchanged)`);
  }
}

async function seedApiClient() {
  const name = "Nivara integration example";
  if (await ApiClient.exists({ name })) {
    console.log("api client: already present (key was shown when it was created)");
    return;
  }
  const prefix = randomBytes(4).toString("hex");
  const secret = randomBytes(24).toString("base64url");
  await ApiClient.create({
    name,
    keyPrefix: prefix,
    keyHash: createHash("sha256").update(secret).digest("hex"),
    scopes: ["interactions:write", "assessments:read", "stream:read"],
    rateLimitPerMin: 120,
  });
  writeFileSync(
    resolve(OUT_DIR, "integration-api-key.txt"),
    `# Integration example API key (synthetic). Shown once.\nAuthorization: ApiKey ${prefix}.${secret}\n`,
    { mode: 0o600 },
  );
  console.log("api client: created (key written to .seed-output/integration-api-key.txt)");
}

async function main() {
  mkdirSync(OUT_DIR, { recursive: true });
  await db();
  const districts = await seedGeography();
  const home = districts.get("MH-PUN");
  if (!home) throw new Error("home district missing");
  await seedUsers(home);
  await seedScoringConfig();
  await seedApiClient();
  await mongoose.disconnect();
}

main().catch(async (err: unknown) => {
  console.error(`seed failed: ${(err as Error).message}`);
  await mongoose.disconnect();
  process.exit(1);
});
